"""Состояние узла для панели провайдера.

Панель работает под тем, кто вошёл в систему, а агент — служебный демон под
своим пользователем. Между ними нужен канал, и это файл, а не сокет и не порт.

Почему файл. Сокет пришлось бы охранять правами и убирать за собой; порт —
охранять тем более, а ещё объяснять брандмауэру. Файл читается кем угодно,
кому его дали прочитать, переживает перезапуск обеих сторон и не требует, чтобы
они запускались в каком-то порядке. Панель, открытая до старта агента, увидит
его отсутствие, а не ошибку соединения.

Пишется целиком и переименованием: панель опрашивает файл раз в две секунды и
однажды попала бы ровно в середину записи. Переименование в пределах одного
тома атомарно, так что читающий видит либо прежнюю версию, либо новую.

Пишущих двое, и у каждого свой файл. Агент рассказывает про железо и задачи —
но только тот агент, который это умеет, а приезжает он по сети, и его версия
та, что выпущена, а не та, что лежит в пакете. Пусковой слой рассказывает то,
что знает точно: какая версия запущена и работает ли она вообще. Слить это в
один файл нельзя — они переписывали бы друг друга, и панель показывала бы то
одно, то другое.
"""

from __future__ import annotations

import json
import logging
import os
from pathlib import Path

logger = logging.getLogger("looma_agent.status")

NAME = "status.json"


def path_for(root: Path, name: str = NAME) -> Path:
    return Path(root) / name


def write(root: Path, snapshot: dict, name: str = NAME) -> None:
    """Оставить снимок состояния для панели. Никогда не роняет агента.

    Панель — удобство; узел, вставший из-за того, что не смог записать файл
    для окна, был бы худшим разменом, какой тут можно придумать.
    """
    target = path_for(root, name)
    tmp = target.with_suffix(".json.new")
    try:
        tmp.write_text(json.dumps(snapshot, ensure_ascii=False, indent=1))
        # Читают все, пишем только мы: панель работает под другим пользователем
        # и должна видеть файл, но не менять его.
        os.chmod(tmp, 0o644)
        os.replace(tmp, target)
    except OSError as exc:
        logger.debug("состояние для панели не записалось: %s", exc)
        try:
            tmp.unlink(missing_ok=True)
        except OSError:
            pass
